#!/usr/bin/env node
// Upsert a podcast guest's bio + short bio by name. Operational tool used by
// the guest-bio agent (see .claude/agents/guest-bio.md); safe to run by hand.
//
// Usage:
//   node scripts/upsert-guest-bio.mjs --name "Jane Doe" --bio-file bio.txt \
//     [--short-bio "One-line summary."] [--episode-title "..."] [--position N] [--dry-run]
//
// Matches an existing guest case-insensitively by name and updates bio /
// short_bio (and episode_title/position if given). If no guest matches, creates
// one — episode_title defaults to "Episode TBD" and position to max+1.
// Requires DATABASE_URL (loaded from .env).
import 'dotenv/config';
import { readFileSync } from 'node:fs';
import postgres from 'postgres';

function arg(flag) {
  const i = process.argv.indexOf(flag);
  return i === -1 ? undefined : process.argv[i + 1];
}
const has = (flag) => process.argv.includes(flag);

const name = arg('--name');
const bioFile = arg('--bio-file');
const shortBio = arg('--short-bio')?.trim();
const episodeTitle = arg('--episode-title')?.trim();
const positionArg = arg('--position');
const dryRun = has('--dry-run');

if (!name || !bioFile) {
  console.error('Required: --name "Guest Name" --bio-file path/to/bio.txt');
  process.exit(1);
}

const bio = readFileSync(bioFile, 'utf8').trim();
if (!bio) {
  console.error(`Bio file ${bioFile} is empty.`);
  process.exit(1);
}
if (/<[a-z][^>]*>/i.test(bio) || (shortBio && /<[a-z][^>]*>/i.test(shortBio))) {
  console.error('Bios must be plain text — the guests page escapes HTML, so tags render literally.');
  process.exit(1);
}

const sql = postgres(process.env.DATABASE_URL);

try {
  const [existing] = await sql`
    SELECT id, name, episode_title, position FROM guests
    WHERE lower(name) = lower(${name.trim()})
  `;

  if (existing) {
    const updates = { bio, short_bio: shortBio ?? null };
    if (episodeTitle) updates.episode_title = episodeTitle;
    if (positionArg !== undefined) updates.position = parseInt(positionArg, 10);

    if (dryRun) {
      console.log(`[dry-run] Would UPDATE guest ${existing.id} (${existing.name}):`);
      console.log(JSON.stringify(updates, null, 2));
    } else {
      await sql`UPDATE guests SET ${sql(updates)} WHERE id = ${existing.id}`;
      console.log(`Updated guest ${existing.id} (${existing.name}).`);
    }
  } else {
    const initials = name.trim().split(/\s+/).filter(Boolean)
      .map((w) => w[0].toUpperCase()).slice(0, 2).join('');
    const [{ next }] = await sql`SELECT COALESCE(MAX(position), 0) + 1 AS next FROM guests`;
    const row = {
      name: name.trim(),
      initials,
      bio,
      short_bio: shortBio ?? null,
      episode_title: episodeTitle || 'Episode TBD',
      position: positionArg !== undefined ? parseInt(positionArg, 10) : Number(next),
    };

    if (dryRun) {
      console.log('[dry-run] Would INSERT new guest:');
      console.log(JSON.stringify(row, null, 2));
    } else {
      // id has no DB-side default (cuid2 is generated by Drizzle in app code), so mint one here
      const { createId } = await import('@paralleldrive/cuid2');
      const [created] = await sql`
        INSERT INTO guests ${sql({ id: createId(), ...row })} RETURNING id, name, position
      `;
      console.log(`Created guest ${created.id} (${created.name}) at position ${created.position}.`);
      if (!episodeTitle) console.log('Episode title defaulted to "Episode TBD" — update it when known.');
    }
  }
} finally {
  await sql.end();
}
